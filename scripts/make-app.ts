#!/usr/bin/env bun
// Builds ~/Applications/TuvaVideos.app: a double-clickable launcher that runs `bun run start` in the checkout
// (starts the server and opens the tab; if the server already runs it only opens the tab) and exits at once.
// The icon is olchey.svg (the favicon) rendered into an .icns with ImageMagick + iconutil.
//
//   bun run app [<checkout dir>]     default: the main checkout this script lives in (worktrees resolve to it)
import { chmodSync, existsSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { $ } from "bun";

const NAME = "TuvaVideos";
const BUNDLE_ID = "com.incoherentthoughts.tuvavideos";

async function mainCheckout(): Promise<string> {
  const here = resolve(import.meta.dir, "..");
  try {
    const common = (await $`git -C ${here} rev-parse --path-format=absolute --git-common-dir`.text()).trim();
    return dirname(common);
  } catch {
    return here;
  }
}

const checkout = process.argv[2] ? resolve(process.argv[2]) : await mainCheckout();
if (!existsSync(join(checkout, "package.json"))) throw new Error(`no package.json in ${checkout}`);
const bun = Bun.which("bun") ?? "/usr/local/bin/bun";
const magick = Bun.which("magick") ?? "/usr/local/bin/magick";
if (!existsSync(magick)) throw new Error("ImageMagick (`magick`) is needed to render the icon: brew install imagemagick");

const appDir = join(homedir(), "Applications", `${NAME}.app`);
const contents = join(appDir, "Contents");
const macos = join(contents, "MacOS");
const res = join(contents, "Resources");
rmSync(appDir, { recursive: true, force: true });
mkdirSync(macos, { recursive: true });
mkdirSync(res, { recursive: true });

// --- icon: the favicon on a transparent canvas with the ~10% margin macOS icons keep around the tile ---
const svg = await Bun.file(join(import.meta.dir, "..", "src", "web", "olchey.svg")).text(); // this script's own copy, not the target checkout's
const inner = svg.replace(/^<\?xml[^>]*>\s*/, "").replace(/<svg\b[^>]*>/, "").replace(/<\/svg>\s*$/, "");
const iconSvg = `<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024"><g transform="translate(100 100) scale(8.24)">${inner}</g></svg>`;
const tmp = join(contents, "iconbuild");
const iconset = join(tmp, `${NAME}.iconset`);
mkdirSync(iconset, { recursive: true });
const iconSvgPath = join(tmp, "icon.svg");
writeFileSync(iconSvgPath, iconSvg);
for (const [px, name] of [[16, "16x16"], [32, "16x16@2x"], [32, "32x32"], [64, "32x32@2x"], [128, "128x128"], [256, "128x128@2x"], [256, "256x256"], [512, "256x256@2x"], [512, "512x512"], [1024, "512x512@2x"]] as const) {
  await $`${magick} -background none -density 300 ${iconSvgPath} -resize ${px}x${px} -depth 8 ${"PNG32:" + join(iconset, `icon_${name}.png`)}`.quiet();
}
await $`iconutil -c icns ${iconset} -o ${join(res, `${NAME}.icns`)}`;
rmSync(tmp, { recursive: true, force: true });

// --- Info.plist: LSUIElement keeps the launcher out of the Dock; the server itself is a plain background process ---
writeFileSync(
  join(contents, "Info.plist"),
  `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>${NAME}</string>
  <key>CFBundleDisplayName</key><string>${NAME}</string>
  <key>CFBundleIdentifier</key><string>${BUNDLE_ID}</string>
  <key>CFBundleVersion</key><string>1</string>
  <key>CFBundleShortVersionString</key><string>0.1.0</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleExecutable</key><string>${NAME}</string>
  <key>CFBundleIconFile</key><string>${NAME}</string>
  <key>LSUIElement</key><true/>
  <key>LSMinimumSystemVersion</key><string>12.0</string>
  <key>NSHighResolutionCapable</key><true/>
</dict>
</plist>
`,
);

// --- launcher: detaches the server so the app exits at once; a second click reaches `launch()` which only opens the tab ---
const launcher = join(macos, NAME);
writeFileSync(
  launcher,
  `#!/bin/bash
# Generated by scripts/make-app.ts; re-run \`bun run app\` after moving the checkout.
export PATH="/usr/local/bin:/opt/homebrew/bin:$PATH"
LOG="$HOME/Library/Application Support/${NAME}/launcher.log"
mkdir -p "$(dirname "$LOG")"
cd ${JSON.stringify(checkout)} || { echo "checkout missing: ${checkout}" >> "$LOG"; exit 1; }
nohup ${JSON.stringify(bun)} run start >> "$LOG" 2>&1 < /dev/null &
disown
`,
);
chmodSync(launcher, 0o755);

// Let LaunchServices notice the new bundle and its icon.
await $`touch ${appDir}`;
await $`/System/Library/Frameworks/CoreServices.framework/Versions/A/Frameworks/LaunchServices.framework/Versions/A/Support/lsregister -f ${appDir}`.quiet().nothrow();
console.log(`${appDir} -> ${checkout}`);
